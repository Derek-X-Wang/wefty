package main

import (
	"bytes"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/Derek-X-Wang/wefty/internal/workflowhelper"
)

func TestWorkflowInitPrintedLocalTag(t *testing.T) {
	const hint = ` (see "Pinned tag" in wefty status)`
	cases := []struct {
		name   string
		config string
		tag    string
		hint   string
	}{
		{name: "installed", config: `{"version":1,"node_id":"Node-A"}`, tag: "wefty:node:node-a"},
		{name: "missing", tag: "<routing-tag>", hint: hint},
		{name: "broken", config: `{"version":`, tag: "<routing-tag>", hint: hint},
		{name: "invalid version", config: `{"version":999,"node_id":"Node-A"}`, tag: "<routing-tag>", hint: hint},
		{name: "old config without node id", config: `{"version":1,"control_socket":"/tmp/old-node.sock"}`, tag: "<routing-tag>", hint: hint},
		{name: "invalid node id", config: `{"version":1,"node_id":"Node-A\n"}`, tag: "<routing-tag>", hint: hint},
		{name: "unreadable", tag: "<routing-tag>", hint: hint},
	}
	for _, language := range []string{"bash", "ts"} {
		for _, test := range cases {
			t.Run(language+"/"+test.name, func(t *testing.T) {
				config := filepath.Join(t.TempDir(), "node.json")
				if test.config != "" {
					if err := os.WriteFile(config, []byte(test.config), 0o600); err != nil {
						t.Fatal(err)
					}
				} else if test.name == "unreadable" {
					// A directory gives a reliable read error, even under root.
					if err := os.Mkdir(config, 0o700); err != nil {
						t.Fatal(err)
					}
				}
				// The environment default and explicit flag must select the same
				// local metadata as exec. A flag wins over an unusable default.
				for _, explicit := range []bool{false, true} {
					parent := t.TempDir()
					t.Setenv("WEFTY_NODE_CONFIG", config)
					args := []string{"--fabric=invalid-must-not-open", "--profile=/unused/broken-profile.json"}
					if explicit {
						t.Setenv("WEFTY_NODE_CONFIG", filepath.Join(t.TempDir(), "absent.json"))
						args = append(args, "--node-config="+config)
					}
					args = append(args, "workflow", "init", "demo", "--lang", language, "--dir", parent)
					var stdout, stderr bytes.Buffer
					if err := run(t.Context(), args, &stdout, &stderr); err != nil {
						t.Fatalf("init must stay offline and tolerate node config errors: %v; stderr=%s", err, &stderr)
					}
					interpreter, script := "bash", "demo.sh"
					if language == "ts" {
						interpreter, script = "node", filepath.Join("dist", "demo.mjs")
					}
					want := "  wefty --json submit --script=" + filepath.Join(parent, "demo", script) +
						" --interpreter=" + interpreter + " --required-envelope --tag=" + test.tag + test.hint + "\n"
					if !strings.HasSuffix(stdout.String(), want) {
						t.Errorf("explicit=%v: printed guidance = %q, want suffix %q", explicit, stdout.String(), want)
					}
					if stderr.Len() != 0 {
						t.Errorf("unexpected warning: %s", &stderr)
					}
					// Local identity belongs only in the printed guidance. Every
					// generated byte must match the machine-independent scaffold.
					reference := t.TempDir()
					if err := workflowhelper.ExecuteWorkflow([]string{"init", "demo", "--lang", language, "--dir", reference}, false, &bytes.Buffer{}); err != nil {
						t.Fatal(err)
					}
					err := filepath.WalkDir(filepath.Join(reference, "demo"), func(path string, entry fs.DirEntry, err error) error {
						if err != nil || entry.IsDir() {
							return err
						}
						rel, err := filepath.Rel(reference, path)
						if err != nil {
							return err
						}
						want, err := os.ReadFile(path)
						if err != nil {
							return err
						}
						got, err := os.ReadFile(filepath.Join(parent, rel))
						if err == nil && !bytes.Equal(got, want) {
							t.Errorf("generated %s changed with local config", rel)
						}
						return err
					})
					if err != nil {
						t.Fatal(err)
					}
				}
			})
		}
	}
}
